#!/usr/bin/env python3
"""Generate evaluation LaTeX tables and optional figures from experiment JSON."""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

try:
    from sklearn.metrics import ConfusionMatrixDisplay, RocCurveDisplay, confusion_matrix
except ImportError:
    ConfusionMatrixDisplay = RocCurveDisplay = confusion_matrix = None  # type: ignore

ROOT = Path(__file__).resolve().parents[1]
EVAL_DIR = ROOT / "latex_dissertation" / "eval"
FIG_DIR = ROOT / "latex_dissertation" / "figures"
TABLES_DIR = ROOT / "latex_dissertation" / "tables"
MANIFEST = ROOT / "extracted_data" / "dataset_manifest.csv"

GNN_MODELS = ["gin", "sage", "gat", "gine"]


def _cell(v, fmt="{:.3f}"):
    if v is None:
        return "--"
    try:
        return fmt.format(float(v))
    except (TypeError, ValueError):
        return "--"


def load_gnn_results() -> dict[str, dict]:
    out = {}
    for m in GNN_MODELS:
        path = ROOT / f"results_{m}_stratified_group.json"
        if path.exists():
            data = json.loads(path.read_text(encoding="utf-8"))
            folds = data.get("fold_results", [])
            if folds:
                correct = [f["correct"] for f in folds]
                out[m] = {
                    "accuracy": float(np.mean(correct)),
                    "n": len(folds),
                    "source": str(path.name),
                }
    return out


def load_tabular() -> dict | None:
    path = EVAL_DIR / "tabular_cv_results.json"
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def load_binary_meta() -> dict | None:
    for rel in ("models/binary_meta.json", "latex_dissertation/eval/binary_meta.json"):
        path = ROOT / rel
        if path.exists():
            return json.loads(path.read_text(encoding="utf-8"))
    return None


def write_eval_tables() -> None:
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    gnn = load_gnn_results()
    tab = load_tabular()
    meta = load_binary_meta()

    lines = [
        "% Auto-generated by scripts/generate_eval_latex.py",
        "% Re-run after: train.py, train_binary_model.py, tabular_baselines.py",
        "",
        "\\subsection{GNN backbone comparison (StratifiedGroupKFold by family)}",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\caption{Held-out GNN results (populate after running \\texttt{train.py}).}",
        "\\label{tab:gnn_comparison}",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "\\textbf{Model} & \\textbf{Precision} & \\textbf{Recall} & \\textbf{F1} & \\textbf{ROC-AUC} \\\\",
        "\\midrule",
    ]
    for m in GNN_MODELS:
        if m in gnn:
            acc = gnn[m]["accuracy"]
            lines.append(f"{m.upper()} & -- & -- & -- & {_cell(acc)} \\\\")
        else:
            lines.append(f"{m.upper()} & -- & -- & -- & -- \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
        "\\subsection{Tabular baselines (manifest graph-level features)}",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\caption{Tabular baseline CV (\\texttt{tabular\\_baselines.py}).}",
        "\\label{tab:tabular_baselines}",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "\\textbf{Model} & \\textbf{Precision} & \\textbf{Recall} & \\textbf{F1} & \\textbf{ROC-AUC} \\\\",
        "\\midrule",
    ]
    if tab:
        for name, block in tab.get("models", {}).items():
            s = block.get("summary", {})
            lines.append(
                f"{name.replace('_', ' ').title()} & "
                f"{_cell(s.get('precision_mean'))} & "
                f"{_cell(s.get('recall_mean'))} & "
                f"{_cell(s.get('f1_mean'))} & "
                f"{_cell(s.get('roc_auc_mean'))} \\\\"
            )
    else:
        lines.append("Logistic Regression & -- & -- & -- & -- \\\\")
        lines.append("Random Forest & -- & -- & -- & -- \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
        "\\subsection{Cross-validation protocol}",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\caption{Evaluation protocol used for reported metrics.}",
        "\\label{tab:cv_protocol}",
        "\\begin{tabular}{ll}",
        "\\toprule",
        "\\textbf{Setting} & \\textbf{Value} \\\\",
        "\\midrule",
        "Split strategy & StratifiedGroupKFold \\\\",
        "Group column & \\texttt{family} \\\\",
        "Folds & 5 (capped by number of families) \\\\",
        "Random seed & 42 \\\\",
        "Exclude uncertain benign & Optional (\\texttt{--exclude-uncertain}) \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ]
    if meta:
        lines += [
            "\\subsection{Binary GINE baseline (single hold-out)}",
            "\\begin{table}[htbp]",
            "\\centering",
            "\\caption{Binary model validation metrics from saved metadata.}",
            "\\label{tab:binary_meta}",
            "\\begin{tabular}{lc}",
            "\\toprule",
            "\\textbf{Metric} & \\textbf{Value} \\\\",
            "\\midrule",
            f"Validation F1 & {_cell(meta.get('best_val_f1'))} \\\\",
            f"AUROC & {_cell(meta.get('val_auroc'))} \\\\",
            f"PR-AUC & {_cell(meta.get('val_pr_auc'))} \\\\",
            f"Precision @ threshold & {_cell(meta.get('val_precision_at_threshold_high'))} \\\\",
            f"Recall @ threshold & {_cell(meta.get('val_recall_at_threshold_high'))} \\\\",
            "\\bottomrule",
            "\\end{tabular}",
            "\\end{table}",
            "",
        ]

    (TABLES_DIR / "eval_results.tex").write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {TABLES_DIR / 'eval_results.tex'}")


def plot_uncertainty_bar() -> None:
    df = pd.read_csv(MANIFEST)
    df["uncertain"] = df["uncertain"].astype(str).str.lower().eq("true")
    benign = df[df["label"] == 0]
    u = int(benign["uncertain"].sum())
    c = len(benign) - u
    fig, ax = plt.subplots(figsize=(4, 3))
    ax.bar(["Uncertain", "Not uncertain"], [u, c], color=["#F58518", "#72B7B2"])
    ax.set_ylabel("Benign-labelled samples")
    ax.set_title("Benign label uncertainty (n=15)")
    fig.tight_layout()
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIG_DIR / "fig_uncertainty_benign.pdf")
    plt.close(fig)


def plot_eval_figures_from_predictions() -> None:
    if confusion_matrix is None:
        return
    pred_path = ROOT / "outputs" / "predictions.csv"
    if not pred_path.exists():
        return
    df = pd.read_csv(pred_path)
    if df.empty or "true" not in df.columns:
        return
    y_true = df["true"].values
    y_pred = df["pred"].values
    y_prob = df["prob"].values if "prob" in df.columns else y_pred.astype(float)

    FIG_DIR.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(4, 4))
    ConfusionMatrixDisplay(confusion_matrix(y_true, y_pred)).plot(ax=ax, cmap="Blues")
    ax.set_title("Confusion matrix (held-out CV)")
    fig.tight_layout()
    fig.savefig(FIG_DIR / "fig_confusion_matrix.pdf")
    plt.close(fig)

    if len(np.unique(y_true)) > 1:
        fig, ax = plt.subplots(figsize=(4, 4))
        RocCurveDisplay.from_predictions(y_true, y_prob, ax=ax)
        ax.plot([0, 1], [0, 1], "k--", alpha=0.4)
        ax.set_title("ROC curve (held-out CV)")
        fig.tight_layout()
        fig.savefig(FIG_DIR / "fig_roc_curve.pdf")
        plt.close(fig)
    print("Wrote eval figures from outputs/predictions.csv")


def main() -> None:
    write_eval_tables()
    plot_uncertainty_bar()
    try:
        plot_eval_figures_from_predictions()
    except Exception as e:
        print(f"Skipping prediction figures: {e}")


if __name__ == "__main__":
    main()
